const DICTS: Record<LanguageCode, Dict> = { en, ru, de, fr, ar };

const STORAGE_KEY = 'nulls.lang';

function isLang(value: unknown): value is LanguageCode {
  return typeof value === 'string' && value in DICTS;
}

function detectBrowserLang(): LanguageCode {
  try {
    const nav = navigator.language?.toLowerCase() ?? '';
    if (nav.startsWith('ru')) return 'ru';
    if (nav.startsWith('de')) return 'de';
    if (nav.startsWith('fr')) return 'fr';
    if (nav.startsWith('ar')) return 'ar';
  } catch {
    // no-op
  }
  return 'en';
}

function readStored(): LanguageCode {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (isLang(raw)) return raw;
  } catch {
    // localStorage unavailable
  }
  return detectBrowserLang();
}

interface I18nContextValue {
  lang: LanguageCode;
  dir: 'ltr' | 'rtl';
  t: (key: string, vars?: Record<string, string | number>) => string;
  setLang: (lang: LanguageCode) => void;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({
  children,
  serverLang,
}: {
  children: ReactNode;
  /** Preferred language from the signed-in user's saved preferences, if any. */
  serverLang?: string;
}) {
  const [lang, setLangState] = useState<LanguageCode>(() => {
    const stored = readStored();
    if (stored !== 'en') return stored;
    // Prefer an explicitly saved server preference over browser detection.
    if (isLang(serverLang) && serverLang !== 'en') return serverLang;
    return stored;
  });

  useEffect(() => {
    const dir = LANGUAGES.find((l) => l.code === lang)?.dir ?? 'ltr';
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
  }, [lang]);

  const setLang = useCallback((next: LanguageCode) => {
    setLangState(next);
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch {
      // no-op
    }
  }, []);

  const t = useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      const dict = DICTS[lang];
      let text = dict[key] ?? en[key] ?? key;
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          text = text.replaceAll(`{${k}}`, String(v));
        }
      }
      return text;
    },
    [lang],
  );

  const value = useMemo<I18nContextValue>(
    () => ({
      lang,
      dir: LANGUAGES.find((l) => l.code === lang)?.dir ?? 'ltr',
      t,
      setLang,
    }),
    [lang, t, setLang],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    throw new Error('useI18n must be used inside <I18nProvider>');
  }
  return ctx;
}

/** Convenience: translated label for a ticket status / verification / etc. */
export function useStatusLabel(kind: 'status' | 'verification' | 'priority' | 'visibility' | 'stage', value: string): string {
  const { t } = useI18n();
  return t(`${kind}.${value}`);
}
